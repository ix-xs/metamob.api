// Writes `src/generated/` from the pinned snapshot of the reference data
// (`scripts/data/snapshot.json`), the description of the endpoints
// (`scripts/api.config.mjs`) and the version in `package.json`.
//
//   node scripts/generate.mjs           # write the files
//   node scripts/generate.mjs --check   # fail when a file is out of date
//
// Never edit `src/generated/` by hand: change the inputs and run this again.

import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { methods } from "./api.config.mjs";
import { loadSnapshot, normalize } from "./snapshot.mjs";

const check = process.argv.includes("--check");
const out = new URL("../src/generated/", import.meta.url);
const HEADER = "// Generated by scripts/generate.mjs. Do not edit: change the inputs and run `npm run generate`.\n";

const snapshot = normalize(await loadSnapshot());
const pkg = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));

// ---------------------------------------------------------------------------
// The data set, as compact rows. Decoded by src/data/dataset.ts.
// ---------------------------------------------------------------------------

/** A translation equal to the French name is stored as 0. */
const names = (name) => [name.fr, name.en === name.fr ? 0 : name.en, name.es === name.fr ? 0 : name.es];

const compact = {
  d: snapshot.fetchedAt,
  gv: snapshot.gameVersions.map((version) => [version.id, version.name]),
  mt: snapshot.monsterTypes.map((type) => [type.id, ...names(type.name)]),
  qt: snapshot.questTypes.map((type) => [type.id, type.slug, ...names(type.name), type.image ?? ""]),
  sv: snapshot.servers.map((server) => [server.id, server.name, server.community, server.game_version ?? 0]),
  tp: snapshot.questTemplates.map((template) => {
    const known = template.monsters.some(([, step]) => step > 0);
    return [template.id, template.quest_type ?? 0, template.game_version ?? 0, template.step_count, template.monsters.map(([id]) => id), known ? template.monsters.map(([, step]) => step) : []];
  }),
  z: snapshot.zones.map((zone) => [zone.id, ...names(zone.name)]),
  sz: snapshot.subzones.map((subzone) => [subzone.id, ...names(subzone.name), subzone.zone, subzone.monsters]),
  m: snapshot.monsters.map((monster) => [monster.id, ...names(monster.name), monster.image, monster.level_min, monster.level_max, monster.type ?? 0, monster.reference ?? 0]),
};

const json = JSON.stringify(compact);
// A single-quoted string: the JSON is full of double quotes and has few apostrophes.
const literal = `'${json.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

const datasetFile = `${HEADER}
/** Day the reference data was fetched from the API, as \`YYYY-MM-DD\`. */
export const DATASET_DATE = ${JSON.stringify(snapshot.fetchedAt)};

/**
 * The reference data of the API as compact JSON. It is parsed on first use,
 * which is faster than an object literal of the same size and costs nothing
 * to programs that never name a monster.
 */
export const DATASET_JSON = ${literal};
`;

// ---------------------------------------------------------------------------
// Names, as string literal unions: what makes an editor suggest "Tofu".
// ---------------------------------------------------------------------------

const union = (name, doc, values, quote = true) => {
  const unique = [...new Set(values)];
  const members = unique.map((value) => `  | ${quote ? JSON.stringify(value) : value}`).join("\n");
  return `/** ${doc} */\nexport type ${name} =\n${members};\n`;
};
const localized = (prefix, doc, records) =>
  ["fr", "en", "es"]
    .map((language) => union(`${prefix}${language[0].toUpperCase()}${language[1]}`, `${doc}, in ${{ fr: "French", en: "English", es: "Spanish" }[language]}.`, records.map((record) => record.name[language])))
    .join("\n");

const namesFile = `${HEADER}
// String literal unions of the names known when the package was built. They
// only feed autocompletion: every method also takes any other string or an id.

${localized("MonsterName", "Name of a monster", snapshot.monsters)}
${localized("ZoneName", "Name of a zone", snapshot.zones)}
${localized("SubzoneName", "Name of a subzone", snapshot.subzones)}
${localized("MonsterTypeName", "Name of a kind of monster", snapshot.monsterTypes)}
${localized("QuestTypeName", "Name of a kind of quest", snapshot.questTypes)}
${union("QuestTypeSlug", "Slug of a kind of quest.", snapshot.questTypes.map((type) => type.slug))}
${union("ServerName", "Name of a game server.", snapshot.servers.map((server) => server.name))}
${union("GameVersionName", "Name of a version of the game.", snapshot.gameVersions.map((version) => version.name))}
${union("QuestTemplateId", "Id of a quest template.", snapshot.questTemplates.map((template) => template.id), false)}`;

// ---------------------------------------------------------------------------
// The endpoints.
// ---------------------------------------------------------------------------

const methodLines = methods.map((method) => {
  const fields = [`id: ${JSON.stringify(method.id)}`, `verb: ${JSON.stringify(method.verb)}`, `path: ${JSON.stringify(method.path)}`, `scope: ${JSON.stringify(method.scope)}`];
  if (method.paged) fields.push(`paged: { max: ${method.paged.max}${method.paged.cursor ? ", cursor: true" : ""} }`);
  return `  ${JSON.stringify(method.id)}: { ${fields.join(", ")} },`;
});

const methodsFile = `${HEADER}
import type { MethodSpec } from "../core/rest.js";

/**
 * Every endpoint of the API, keyed by the name the library gives it. The
 * names are the ones used in cache settings, in events and in errors.
 */
export const METHODS = {
${methodLines.join("\n")}
} as const satisfies Record<string, MethodSpec>;

/** Name of an endpoint, for example \`monsters.get\`. */
export type MethodId = keyof typeof METHODS;
`;

const versionFile = `${HEADER}
/** Version of the package. */
export const VERSION = ${JSON.stringify(pkg.version)};
`;

// ---------------------------------------------------------------------------

const files = { "dataset.ts": datasetFile, "names.ts": namesFile, "methods.ts": methodsFile, "version.ts": versionFile };

let stale = 0;
await mkdir(out, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  const url = new URL(name, out);
  const current = existsSync(url) ? (await readFile(url, "utf8")).replace(/\r\n/g, "\n") : undefined;
  if (current === content) continue;
  stale++;
  if (check) console.error(`src/generated/${name} is out of date`);
  else await writeFile(url, content);
}

if (check && stale) {
  console.error("\nRun `npm run generate` and commit the result.");
  process.exit(1);
}
console.log(
  check
    ? `generated files are up to date (${Object.keys(files).length} files)`
    : `generated ${Object.keys(files).length} files: ${snapshot.monsters.length} monsters, ${snapshot.zones.length} zones, ${snapshot.subzones.length} subzones, ${methods.length} methods, data set ${(json.length / 1024).toFixed(0)} kB`,
);
